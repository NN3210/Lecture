put(15, '3-1 軸を回す座標変換', r'''
原点を $(x_0,y_0)$ に移し、軸を反時計回りに $\theta$ 回す。

$$
\begin{aligned}
x'&=(x-x_0)\cos\theta+(y-y_0)\sin\theta\\
y'&=-(x-x_0)\sin\theta+(y-y_0)\cos\theta
\end{aligned}
$$

- 点は動かさず、**同じ点を別の座標で読む**。
- 平行移動と回転では、点間距離・角・形は変わらない。
- 縮尺も変える相似変換では、角は保たれ、距離は倍率分変わる。
''')
